print(s[0] if -len(s) <= 0 < len(s) else 'OOR')
print(s[-1] if -len(s) <= -1 < len(s) else 'OOR')
print(s[1] if -len(s) <= 1 < len(s) else 'OOR')
print(s[20] if -len(s) <= 20 < len(s) else 'OOR')
